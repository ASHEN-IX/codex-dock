//! Native platform process discovery for Codex Desktop.
//!
//! Provides a platform-neutral interface to detect running Codex Desktop instances,
//! inspect executable paths, correlate processes with managed profiles when
//! evidence exists, and handle access-denied and transient-exit races.

#[cfg(target_os = "linux")]
mod linux;
#[cfg(target_os = "macos")]
mod macos;
#[cfg(not(any(target_os = "linux", target_os = "macos", target_os = "windows")))]
mod stub;
#[cfg(target_os = "windows")]
mod windows;

use crate::accounts::Account;
use crate::error::Result;
use crate::paths::Paths;
use std::path::{Path, PathBuf};

/// Attribution of a discovered Codex Desktop process to a managed profile.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ProfileAttribution {
    /// Process is confidently associated with a known managed profile.
    Known(String),
    /// Process is a confirmed Codex Desktop process, but its profile is unknown or unverified.
    Unknown,
}

/// A discovered running Codex Desktop process.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DiscoveredProcess {
    pub pid: u32,
    pub exe_path: Option<PathBuf>,
    pub attribution: ProfileAttribution,
    pub user_data_dir: Option<PathBuf>,
}

/// The report generated by a native process discovery scan.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProcessDiscoveryReport {
    /// Discovered Codex Desktop processes.
    pub processes: Vec<DiscoveredProcess>,
    /// Warnings or restrictions encountered during scanning.
    pub warnings: Vec<String>,
}

/// Outcome of querying running Codex processes for an account or system.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DiscoveryOutcome {
    /// Process confidently belongs to a managed profile.
    ManagedProfile(DiscoveredProcess),
    /// Codex process found, profile unknown.
    UnknownProfile(DiscoveredProcess),
    /// No Codex process found.
    NoCodexProcess,
    /// Inspection incomplete or denied.
    InspectionIncompleteOrDenied(String),
    /// Discovery unsupported on this platform.
    Unsupported(String),
}

/// Check if an executable image filename is a candidate for Codex Desktop.
pub fn is_candidate_codex_name(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    let stem = lower.strip_suffix(".exe").unwrap_or(&lower);
    matches!(stem, "codex" | "chatgpt" | "codex-desktop")
}

/// Check if a process is an Electron helper surface (renderer, GPU, utility).
pub fn is_electron_helper(exe_name: &str, args: &[String]) -> bool {
    let lower = exe_name.to_ascii_lowercase();
    if lower.contains("helper") {
        return true;
    }
    args.iter().any(|arg| arg.starts_with("--type="))
}

/// Extract `--user-data-dir` argument from a command-line token list.
pub fn extract_user_data_dir(args: &[String]) -> Option<PathBuf> {
    const FLAG: &str = "--user-data-dir=";
    if let Some(arg) = args.iter().find_map(|s| s.strip_prefix(FLAG)) {
        return Some(PathBuf::from(arg.trim_matches('"')));
    }
    let mut it = args.iter();
    while let Some(arg) = it.next() {
        if arg == "--user-data-dir" {
            if let Some(next) = it.next() {
                return Some(PathBuf::from(next.trim_matches('"')));
            }
        }
    }
    None
}

/// Associate a process with a managed profile based on verified evidence.
///
/// If `--user-data-dir` or `CODEX_HOME` points to a known managed profile,
/// attributes the process to that profile (`ProfileAttribution::Known`).
/// If evidence is absent, ambiguous, or points to an unmanaged location,
/// returns `ProfileAttribution::Unknown`.
///
/// An unknown process is NEVER assigned to an arbitrary or default account.
pub fn attribute_process(
    user_data_dir: Option<&Path>,
    codex_home: Option<&Path>,
    managed_profiles: &[Account],
) -> ProfileAttribution {
    // 1. Try matching by --user-data-dir directory name prefix:
    if let Some(udd) = user_data_dir {
        if let Some(file_name) = udd.file_name().and_then(|n| n.to_str()) {
            if let Some(candidate_name) = file_name.strip_prefix("Codex-") {
                if !candidate_name.is_empty()
                    && managed_profiles.iter().any(|a| a.name == candidate_name)
                {
                    return ProfileAttribution::Known(candidate_name.to_string());
                }
            }
        }
    }

    // 2. Try matching by CODEX_HOME environment path:
    if let Some(home) = codex_home {
        if let Some(account) = managed_profiles.iter().find(|a| a.path == home) {
            return ProfileAttribution::Known(account.name.clone());
        }
    }

    // 3. Fallback: unknown profile
    ProfileAttribution::Unknown
}

/// procfs root on Linux, `None` anywhere without one (macOS, Windows, BSD).
pub fn proc_root() -> Option<PathBuf> {
    #[cfg(target_os = "linux")]
    {
        if supported() {
            Some(PathBuf::from("/proc"))
        } else {
            None
        }
    }
    #[cfg(not(target_os = "linux"))]
    {
        None
    }
}

/// Whether native process discovery is supported on this platform.
pub fn supported() -> bool {
    matches!(
        crate::platform::capabilities().native_process_discovery,
        crate::platform::Support::Yes
    )
}

/// Method used for native process discovery on the current platform.
pub fn discovery_method() -> &'static str {
    #[cfg(target_os = "linux")]
    {
        "Linux procfs (/proc)"
    }
    #[cfg(target_os = "macos")]
    {
        "macOS libproc & sysctl(KERN_PROCARGS2)"
    }
    #[cfg(target_os = "windows")]
    {
        "Windows Win32 Toolhelp32 & QueryFullProcessImageNameW"
    }
    #[cfg(not(any(target_os = "linux", target_os = "macos", target_os = "windows")))]
    {
        "unsupported"
    }
}

/// Scan running processes natively on the current operating system.
pub fn scan_processes(p: &Paths) -> Result<ProcessDiscoveryReport> {
    if !supported() {
        return Err(crate::error::Error::Msg(
            "native process discovery is not supported on this platform".to_string(),
        ));
    }

    #[cfg(target_os = "linux")]
    {
        linux::scan_processes(p)
    }
    #[cfg(target_os = "macos")]
    {
        macos::scan_processes(p)
    }
    #[cfg(target_os = "windows")]
    {
        windows::scan_processes(p)
    }
    #[cfg(not(any(target_os = "linux", target_os = "macos", target_os = "windows")))]
    {
        stub::scan_processes(p)
    }
}

/// Query Codex process status for a specific managed account.
pub fn query_account(p: &Paths, account_name: &str) -> DiscoveryOutcome {
    if !supported() {
        return DiscoveryOutcome::Unsupported(
            "native process discovery is not supported on this platform".to_string(),
        );
    }

    let report = match scan_processes(p) {
        Ok(r) => r,
        Err(e) => return DiscoveryOutcome::InspectionIncompleteOrDenied(e.to_string()),
    };

    // First check if a process confidently belongs to this account:
    for proc in &report.processes {
        if proc.attribution == ProfileAttribution::Known(account_name.to_string()) {
            return DiscoveryOutcome::ManagedProfile(proc.clone());
        }
    }

    // Next check if any unknown Codex process is running:
    for proc in &report.processes {
        if proc.attribution == ProfileAttribution::Unknown {
            return DiscoveryOutcome::UnknownProfile(proc.clone());
        }
    }

    DiscoveryOutcome::NoCodexProcess
}

#[cfg(target_os = "linux")]
pub fn scan_processes_at(p: &Paths, proc_root: &Path) -> Result<ProcessDiscoveryReport> {
    linux::scan_processes_at(p, proc_root)
}
